"""Render a market-entry strategy file with the promoted configuration baked in.

The house engine calls ``evaluate(bars, {})`` -- no params argument -- and the
live path merges the ACTIVE ROW's params_json over the code defaults.  So the
only way the backtest stamp and the live fire can describe the SAME strategy
is for the configuration to live in the code's DEFAULTS *and* in the candidate
row.  This script writes the rendered file.

Usage:
  .venv/bin/python research/cycle_20261026/render_code.py \
      <base_file> <out_file> '<json params>'
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

BASE_DEFAULTS_RE = re.compile(r"DEFAULTS = \{.*?\n\}\n", re.S)


def render(base: Path, out: Path, params: dict) -> None:
    src = base.read_text()
    lines = ["DEFAULTS = {"]
    for k, v in params.items():
        lines.append(f"    {k!r}: {v!r},")
    lines.append("}\n")
    block = "\n".join(lines)
    new, n = BASE_DEFAULTS_RE.subn(block, src, count=1)
    if n != 1:
        raise SystemExit(f"no DEFAULTS block found in {base}")
    hdr = (f'"""RENDERED market-entry strategy -- promoted configuration.\n\n'
           f"Generated by research/cycle_20261026/render_code.py from {base.name}.\n"
           f"DO NOT EDIT BY HAND: re-render instead.\n\n"
           f"Every entry is the DECISION BAR'S CLOSE (honest fill: findings\n"
           f"#9126/#9133/#9139/#9146 -- the house backtester fills at the price a\n"
           f"strategy NAMES, so a structural entry price is a retro-fill).\n"
           f'"""\n')
    # keep the module docstring, replace the body after it
    m = re.match(r'\A""".*?"""\n', new, re.S)
    body = new[m.end():] if m else new
    out.write_text(hdr + body)
    print(f"wrote {out} ({len(out.read_text())} bytes)")


if __name__ == "__main__":
    base = Path(sys.argv[1])
    out = Path(sys.argv[2])
    params = json.loads(sys.argv[3])
    render(base, out, params)
